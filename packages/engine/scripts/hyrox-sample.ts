function describe(w: PlannedWorkout): string {
  const lines = [`**${w.title}** (~${w.estimatedMinutes} min)`];
  for (const s of w.steps) {
    if (s.station) {
      const alt = s.station.alternatives.slice(0, 2).map((a) => a.name).join(", ");
      lines.push(`  - ${s.repeat ? `${s.repeat} × ` : ""}${s.station.volume} — ${s.station.recommended?.name ?? "no option"}${s.station.raceLoad ? ` @ ${s.station.raceLoad}` : ""}${alt ? ` _(or: ${alt})_` : ""}`);
    } else if (w.sport === "strength" && s.kind === "steady") {
      lines.push(`  - ${s.note}`);
    } else if (s.kind === "work" || s.kind === "steady") {
      const dist = s.distanceMeters ? `${s.distanceMeters / 1000} km` : `${Math.round((s.durationSeconds ?? 0) / 60)} min`;
      const pace = s.target.pace ? `${formatPace(s.target.pace.fastSecPerKm)}–${formatPace(s.target.pace.slowSecPerKm)}` : `RPE ${s.target.rpe.min}–${s.target.rpe.max}`;
      lines.push(`  - ${s.repeat ? `${s.repeat} × ` : ""}${dist} @ ${pace}`);
    }
  }
  return lines.join("\n");
}

export function render(): string {
  const out: string[] = ["# HYROX sample plans for coach review", "", `Generated by the engine for a race on 2027-02-27, plan starting ${TODAY}. Synthetic athletes only.`, ""];
  for (const { label, athlete, goal } of SAMPLE_ATHLETES) {
    const plan = generateHyroxPlan(athlete, goal, { planId: athlete.id, today: TODAY, now: `${TODAY}T12:00:00-06:00` });
    out.push(`## ${label}`, "");
    if (plan.basis.notes.length) out.push(...plan.basis.notes.map((n) => `> ${n}`), "");
    out.push("| Week | Phase | Run km | Sessions | Simulation |", "|---|---|---|---|---|");
    for (const wk of plan.weeks) {
      const sim = wk.workouts.find((w) => w.type === "full_simulation" || w.type === "half_simulation");
      out.push(`| ${wk.index + 1} (${wk.startDate}) | ${wk.phase}${wk.isRecoveryWeek ? " (recovery)" : ""} | ${Math.round(wk.targetRunMeters / 1000)} | ${wk.workouts.length} | ${sim ? `${sim.title} on ${sim.date}` : ""} |`);
    }
    const buildWeek = plan.weeks.find((w) => w.phase === "build" && !w.isRecoveryWeek && !w.workouts.some((x) => x.type.endsWith("simulation"))) ?? plan.weeks[0]!;
    out.push("", `### Example build week (week ${buildWeek.index + 1})`, "");
    for (const w of buildWeek.workouts) {
      const d = new Date(`${w.date}T00:00:00Z`);
      out.push(`- ${DAY[(d.getUTCDay() + 6) % 7]} ${w.date}: ${describe(w)}`);
    }
    out.push("");
  }
  return out.join("\n");
}

