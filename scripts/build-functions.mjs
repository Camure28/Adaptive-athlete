// Bundles the training engine into one file for the Supabase Edge Functions (Deno), so the server
// runs exactly the engine code in this repo. Output is git-ignored; `pnpm functions:deploy` rebuilds it.
import { build } from "esbuild";

await build({
  entryPoints: ["packages/engine/src/index.ts"],
  outfile: "supabase/functions/_shared/engine.js",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  banner: { js: "// GENERATED by scripts/build-functions.mjs from packages/engine. Do not edit." },
  logLevel: "info",
});
